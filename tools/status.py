#!/usr/bin/env python3
"""Regenerate REVIEW_STATUS.md from the catalogs under versions/.

Each entry falls in exactly one bucket:
  reviewed (here)      translated, not fuzzy, no seed comment
  reviewed (upstream)  translated, not fuzzy, comment "Seeded from ... (reviewed upstream)"
  fuzzy (AI draft)     flagged fuzzy (machine draft, or a seed that failed a check)
  untranslated         empty msgstr (or a plural entry with any empty form)

Usage: python tools/status.py [--check]   (--check: exit 1 if the file is stale)
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import load  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "REVIEW_STATUS.md"
LANG_ORDER = ["sr_Latn", "sr", "hr", "bs"]


def classify(msg) -> str:
    strings = list(msg.string) if isinstance(msg.string, (tuple, list)) else [msg.string]
    if msg.fuzzy:
        return "fuzzy"
    if not strings or not all(strings):
        return "untranslated"
    if any("(reviewed upstream)" in c for c in msg.user_comments):
        return "upstream"
    return "reviewed"


def version_key(p: Path):
    return tuple(int(x) if x.isdigit() else x for x in p.name.split("."))


def render() -> str:
    rows = []
    for vdir in sorted((ROOT / "versions").glob("*"), key=version_key):
        langs = {p.parent.parent.name: p for p in vdir.glob("superset/translations/*/LC_MESSAGES/messages.po")}
        for lang in sorted(langs, key=lambda x: (LANG_ORDER.index(x) if x in LANG_ORDER else 99, x)):
            c = Counter(classify(m) for m in load(langs[lang]) if m.id)
            total = sum(c.values())
            done = c["reviewed"] + c["upstream"]
            rows.append(f"| {vdir.name} | `{lang}` | {total} | {c['reviewed']} | {c['upstream']} | "
                        f"{c['fuzzy']} | {c['untranslated']} | {done / total:.1%} |")
    lines = [
        "# Review status",
        "",
        "_Generated by `tools/status.py`. Do not edit by hand._",
        "",
        "- **Reviewed (here)**: reviewed by a native speaker in this repository.",
        "- **Reviewed (upstream)**: copied unchanged from a human-reviewed apache/superset catalog",
        "  (exact msgid match; the entry's comment names the commit).",
        "- **Fuzzy (AI draft)**: machine draft, shown in the UI, waiting for native review.",
        "",
        "| Version | Language | Total | Reviewed (here) | Reviewed (upstream) | Fuzzy (AI draft) | Untranslated | Reviewed % |",
        "|---------|----------|------:|----------------:|--------------------:|-----------------:|-------------:|-----------:|",
        *rows,
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if REVIEW_STATUS.md is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("REVIEW_STATUS.md is stale; run tools/status.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
